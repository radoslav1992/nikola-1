/**
 * Builds src/data/settlements.js — every Bulgarian city, town and village with its province
 * and approximate centre, used for "near X" distances and map markers.
 *
 * Source: settlements_loc.csv from https://github.com/yurukov/Bulgaria-geocoding
 * (names and EKATTE codes from the National Statistical Institute; coordinates extracted from
 * OpenStreetMap, © OpenStreetMap contributors, ODbL).
 *
 *   curl -sO https://raw.githubusercontent.com/yurukov/Bulgaria-geocoding/master/settlements_loc.csv
 *   node scripts/build-settlements.mjs settlements_loc.csv
 *
 * Row format: [name, lat, lng, province index, isTown]
 */
import { readFileSync, writeFileSync } from 'node:fs';

const file = process.argv[2];
if (!file) throw new Error('Usage: node scripts/build-settlements.mjs settlements_loc.csv');

function parseCsv(text) {
  const rows = [];
  for (const line of text.split(/\r?\n/)) {
    if (!line.trim()) continue;
    const cells = [];
    let cell = '';
    let quoted = false;
    for (let i = 0; i < line.length; i++) {
      const ch = line[i];
      if (quoted) {
        if (ch === '"' && line[i + 1] === '"') (cell += '"'), i++;
        else if (ch === '"') quoted = false;
        else cell += ch;
      } else if (ch === '"') quoted = true;
      else if (ch === ',') cells.push(cell), (cell = '');
      else cell += ch;
    }
    cells.push(cell);
    rows.push(cells);
  }
  return rows;
}

const [header, ...records] = parseCsv(readFileSync(file, 'utf8'));
const col = (name) => header.indexOf(name);
const [cVillage, cName, cProvince, cGeo] = ['village', 'name', 'province', 'geo'].map(col);
if ([cVillage, cName, cProvince, cGeo].includes(-1)) throw new Error('Unexpected CSV header: ' + header.join(','));

const provinces = [...new Set(records.map((r) => r[cProvince]))].sort((a, b) => a.localeCompare(b, 'bg'));
const rows = [];
for (const r of records) {
  const [lng, lat] = String(r[cGeo]).split(',').map(Number);
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) continue;
  if (lat < 41 || lat > 44.3 || lng < 22.3 || lng > 28.7) throw new Error('Outside Bulgaria: ' + r.join(','));
  rows.push([r[cName].trim(), +lat.toFixed(4), +lng.toFixed(4), provinces.indexOf(r[cProvince]), r[cVillage] === '0' ? 1 : 0]);
}
rows.sort((a, b) => a[3] - b[3] || a[0].localeCompare(b[0], 'bg'));

writeFileSync(
  new URL('../src/data/settlements.js', import.meta.url),
  `// Generated by scripts/build-settlements.mjs — do not edit by hand.
// Names: National Statistical Institute (EKATTE). Coordinates: © OpenStreetMap contributors (ODbL),
// compiled by https://github.com/yurukov/Bulgaria-geocoding. Settlement centres only.
export const PROVINCES = ${JSON.stringify(provinces)};
// [name, lat, lng, province index, isTown]
export const SETTLEMENTS = [
${rows.map((row) => JSON.stringify(row)).join(',\n')}
];
`,
);
console.log(`${rows.length} settlements in ${provinces.length} provinces`);
